const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const filename = require('node:path').join(__dirname, '../src/lib/artists/works.ts');
const source = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {}, URL }; vm.runInNewContext(source, context);
const { artistWorks } = context.exports;
const id = '58dbaaca-1324-4e5b-b454-464766a92620';
const row = { id: 'song', title: 'Original', status: 'completed', created_at: '2026-10-05T00:00:00Z', audio_url: 'https://example.test/audio.mp3', cover_art_url: 'https://example.test/cover.png', license_hash: JSON.stringify({ artistId: id, artistRevision: 2, providerSecret: 'never exposed' }) };
assert.equal(artistWorks([row], id).length, 1);
assert.equal(artistWorks([row], id)[0].artistRevision, 2);
assert.equal('license_hash' in artistWorks([row], id)[0], false);
assert.equal('providerSecret' in artistWorks([row], id)[0], false);
assert.equal(artistWorks([row], 'other-artist').length, 0);
assert.equal(artistWorks([{ ...row, license_hash: '{malformed' }], id).length, 0);
assert.equal(artistWorks([{ ...row, license_hash: JSON.stringify({ artistId: id, artistRevision: '2' }) }], id).length, 0);
assert.equal(artistWorks([{ ...row, status: 'generating' }], id)[0].audioUrl, null);
assert.equal(artistWorks([{ ...row, audio_url: 'javascript:alert(1)', cover_art_url: 'https://user:password@example.test/image' }], id)[0].audioUrl, null);
assert.equal(artistWorks([{ ...row, cover_art_url: 'data:invalid' }], id)[0].coverArtUrl, null);
assert.equal(artistWorks(Array.from({ length: 70 }, () => row), id).length, 50);
console.log('artist works: 10 checks passed');
